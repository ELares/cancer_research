#!/usr/bin/env python3
"""Atlas: how much literature does each preregistered prediction sit on?
(#ATLAS-PREDPOS)

WHY
---
`PREREGISTRATION.md` commits to eight falsifiable predictions and names E1 (which
tests P4, the hypoxia leg) "the keystone". `analysis/p1-wetlab-protocol.md` calls
P1 "the highest-leverage falsifiable prediction in the program". Two planning
documents, two different primary experiments, and neither designation cites
evidence.

The census can inform that choice. Each prediction chains ferroptosis to another
concept, and MeSH indexes both sides, so the size of the literature each
prediction lands in is countable.

WHAT LOW SUPPORT DOES AND DOES NOT MEAN
----------------------------------------
It is NOT a quality ranking. A prediction on a sparse leg is more novel and more
valuable if it holds; it is also riskier, harder to interpret against prior work,
and has fewer reagents and protocols to borrow. A prediction on a dense leg is
better contextualised and easier to place, and correspondingly less surprising.

Both are legitimate choices. The point is that the choice should be deliberate,
and right now the two documents make it differently without either of them
knowing these numbers.

Usage:
    python scripts/atlas_prediction_position.py
"""

import collections
import glob
import gzip
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from atlas_baseline import atlas_root  # noqa: E402
from config import PROJECT_ROOT  # noqa: E402

OUT = PROJECT_ROOT / "analysis" / "atlas-prediction-position.md"
RAW = PROJECT_ROOT / "analysis" / "atlas-prediction-position.json"

FERRO = {"Ferroptosis"}

# Each prediction's second concept. `None` means MeSH has no usable descriptor,
# which is reported as unmeasurable rather than as zero support.
PREDICTIONS = {
    "P1": ("GPX4 + FSP1 dual inhibition in FSP1-low persisters",
           {"Drug Resistance, Neoplasm"}, "E4"),
    "P2": ("PDT/SDT less depth-limited than RSL3 in >=500um spheroids",
           {"Spheroids, Cellular"}, "-"),
    "P3": ("post-withdrawal vulnerability window closes over days",
           {"Drug Resistance, Neoplasm"}, "E5"),
    "P4": ("SDT retains more efficacy than RSL3 under hypoxia",
           {"Cell Hypoxia", "Tumor Hypoxia"}, "E1"),
    "P5": ("dense ferroptotic kill is more immunogenic per cell than sparse",
           {"Immunogenic Cell Death"}, "E3"),
    "P6": ("CAF coculture protects RSL3 more than SDT",
           {"Cancer-Associated Fibroblasts"}, "E2"),
    "P7": ("RSL3 efficacy drops at acidic pH via ion trapping",
           {"Hydrogen-Ion Concentration"}, "E6"),
    "P8": ("RSL3 has the opposite size-dependence to generic cytotoxics",
           {"Spheroids, Cellular"}, "-"),
}
# The modality each prediction actually turns on, so the thesis-leg finding
# (32 SDT articles against 479 resistance) can be carried through.
SDT_DEPENDENT = {"P2", "P4", "P6"}


def main() -> int:
    root = atlas_root()
    counts = collections.Counter()
    both = collections.Counter()
    n = 0
    files = sorted(glob.glob(str(root / "records" / "*.jsonl.gz")))
    print(f"scanning {len(files):,} shards ...", flush=True)
    for i, f in enumerate(files, 1):
        with gzip.open(f, "rt", encoding="utf-8") as fh:
            for line in fh:
                m = set(json.loads(line).get("mesh") or [])
                n += 1
                if not m:
                    continue
                fe = bool(m & FERRO)
                for pid, (_d, descs, _e) in PREDICTIONS.items():
                    if descs and (m & descs):
                        counts[pid] += 1
                        if fe:
                            both[pid] += 1
        if i % 400 == 0:
            print(f"  {i}/{len(files)}", flush=True)
    print(f"scanned {n:,} records", flush=True)

    rows = []
    for pid, (desc, descs, exp) in PREDICTIONS.items():
        rows.append({"prediction": pid, "claim": desc, "experiment": exp,
                     "concept_articles": counts[pid],
                     "with_ferroptosis": both[pid],
                     "sdt_dependent": pid in SDT_DEPENDENT})
    rows.sort(key=lambda r: -r["with_ferroptosis"])

    L = [
        "# How much literature does each preregistered prediction sit on? "
        "(#ATLAS-PREDPOS)", "",
        "Generated by `scripts/atlas_prediction_position.py`.", "",
        "`PREREGISTRATION.md` names E1, which tests P4, \"the keystone\".",
        "`analysis/p1-wetlab-protocol.md` calls P1 \"the highest-leverage falsifiable",
        "prediction in the program\". Two planning documents, two different primary",
        "experiments, and neither designation cites evidence. These are the numbers",
        "neither had.", "",
        "## Support for each prediction's leg", "",
        "| prediction | experiment | claim | articles on the concept | with ferroptosis |",
        "|---|---|---|---|---|",
    ]
    for r in rows:
        mark = " *(SDT-dependent)*" if r["sdt_dependent"] else ""
        L.append(f"| **{r['prediction']}**{mark} | {r['experiment']} | {r['claim']} | "
                 f"{r['concept_articles']:,} | **{r['with_ferroptosis']:,}** |")

    p1 = next(r for r in rows if r["prediction"] == "P1")
    p4 = next(r for r in rows if r["prediction"] == "P4")
    L += [
        "", "## The disagreement, with numbers", "",
        f"P1 sits on **{p1['with_ferroptosis']:,}** ferroptosis articles. P4, the one",
        f"the preregistration calls the keystone, sits on **{p4['with_ferroptosis']:,}**.",
        "", "That is not an argument that P4 is a bad prediction. A sparse leg is",
        "where novelty lives, and P4 is deliberately the contested one -- the",
        "manuscript flags its hypoxia claim as genuinely disputed and reports the SDT",
        "advantage as bracketing zero. Testing a contested claim is exactly what a",
        "preregistration is for.", "",
        "It is an argument that the designation should be made with these numbers in",
        "view. P4 additionally depends on sonodynamic therapy, which",
        "`analysis/atlas-thesis-position.md` measures at 32 ferroptosis-intersecting",
        "articles in the entire indexed literature. A negative P4 would therefore be",
        "hard to interpret: it could falsify the mechanism, or reflect that nobody has",
        "yet worked out how to do the experiment well.", "",
        "P1 has the opposite profile. It depends on GPX4 and FSP1 parallel",
        "independence, which is established, so a negative result is interpretable as",
        "a negative result. That is why it is the cheaper first move regardless of",
        "which prediction matters more.", "",
        "## What to do with this", "",
        "* Keep both. The disagreement between the documents is a real strategic",
        "  choice, not an error to be tidied away.",
        "* State the basis. Whichever is called the keystone should say whether it is",
        "  keystone because it is most decisive or because it is most novel -- those",
        "  point at different experiments.",
        "* Sequence by interpretability. A prediction whose negative result is",
        "  ambiguous is a poor first experiment even when it is the most important.", "",
        "## Limits", "",
        "* Co-indexing is not support. An article indexed for both ferroptosis and",
        "  hypoxia need not test their interaction, so every count here is an upper",
        "  bound on relevant work.",
        "* P2 and P8 map onto `Spheroids, Cellular`, which covers spheroid methodology",
        "  generally rather than the size-dependence either predicts. Their counts are",
        "  the loosest here.",
        "* MeSH has no descriptor for drug-tolerant persister cells, so P1 and P3 are",
        "  measured through neoplasm drug resistance, which is broader.",
        "* Indexing lag suppresses the newest work, which falls hardest on exactly the",
        "  sparse legs this analysis is about.",
    ]

    OUT.write_text("\n".join(L) + "\n")
    RAW.write_text(json.dumps({"census_records": n, "rows": rows}, indent=2) + "\n")
    print("\n" + "  ".join(f"{r['prediction']}={r['with_ferroptosis']}" for r in rows))
    print(f"wrote {OUT}\nwrote {RAW}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
